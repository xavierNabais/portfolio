let currentLang = localStorage.getItem('lang') || 'pt';

function t(key) {
  return (legalI18n[currentLang] && legalI18n[currentLang][key]) || legalI18n.pt[key] || key;
}

function setLanguage(lang) {
  currentLang = lang === 'en' ? 'en' : 'pt';
  localStorage.setItem('lang', currentLang);
  document.documentElement.lang = currentLang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const value = t(key);
    if (value) el.innerHTML = value;
  });

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });

  const titleKey = document.body.querySelector('h1')?.getAttribute('data-i18n');
  if (titleKey === 'privacy.title') {
    document.title = `${t('privacy.title')} | Xavier Nabais`;
  } else if (titleKey === 'terms.title') {
    document.title = `${t('terms.title')} | Xavier Nabais`;
  }
}

document.querySelectorAll('.lang-btn').forEach(btn => {
  btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
});

setLanguage(currentLang);
